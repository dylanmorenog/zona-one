export function Sidebar({ rol }: { rol: Rol }) {
  const pathname = usePathname();

  const itemsVisibles = navItems.filter(
    (item) => !item.soloAdmin || rol === "DUENO"
  );

  const generales = itemsVisibles.filter((i) => !i.soloAdmin);
  const admin = itemsVisibles.filter((i) => i.soloAdmin);

  function NavLink({ item }: { item: NavItem }) {
    const activo = pathname === item.href;
    return (
      <Link
        href={item.href}
        className={`flex items-center gap-3 px-3 py-2.5 rounded-lg text-sm transition-all ${
          activo
            ? "bg-brand-600/15 text-brand-400 font-medium"
            : "text-gray-400 hover:text-gray-100 hover:bg-gray-800"
        }`}
      >
        <span className={activo ? "text-brand-400" : "text-gray-500"}>
          {item.icon}
        </span>
        {item.label}
      </Link>
    );
  }

  return (
    <aside className="w-56 shrink-0 flex flex-col bg-gray-900 border-r border-gray-800 h-screen">
      {/* Logo */}
      <div className="flex items-center gap-2.5 px-4 py-5 border-b border-gray-800">
        <div className="w-9 h-9 rounded-full overflow-hidden shrink-0">
          <Image src="/logo.png" alt="Zona One" width={36} height={36} />
        </div>
        <span className="font-bold text-white text-base">Zona One</span>
      </div>

      {/* Navegación principal */}
      <nav className="flex-1 px-3 py-4 space-y-1 overflow-y-auto">
        {generales.map((item) => (
          <NavLink key={item.href} item={item} />
        ))}

        {admin.length > 0 && (
          <>
            <div className="pt-4 pb-1 px-1">
              <p className="text-xs font-medium text-gray-600 uppercase tracking-wider">
                Administración
              </p>
            </div>
            {admin.map((item) => (
              <NavLink key={item.href} item={item} />
            ))}
          </>
        )}
      </nav>
    </aside>
  );
}
